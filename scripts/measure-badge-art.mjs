#!/usr/bin/env node
/*
  Measures each badge PNG in public/badges and writes where its drawn frame
  sits, as percentages of the canvas, to
  src/components/features/guest-app/rewards/badge-art-bounds.ts.

  The coin on the badge detail page fills the open frame with a plate and
  stacks rim slices behind it; both are clipped to these bounds so they sit
  under the frame instead of spilling past it. Re-run after adding or
  regenerating artwork:

    node scripts/measure-badge-art.mjs
*/
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';

const DIR = 'public/badges';
const OUT = 'src/components/features/guest-app/rewards/badge-art-bounds.ts';
/** Alpha above which a pixel counts as frame rather than soft glow. */
const SOLID = 60;

const rows = [];
for (const file of readdirSync(DIR).filter((name) => name.endsWith('.png')).sort()) {
  const { data, info } = await sharp(join(DIR, file)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  let top = h, bottom = 0, left = w, right = 0;
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < w; x += 1) {
      if (data[(y * w + x) * 4 + 3] <= SOLID) continue;
      if (y < top) top = y;
      if (y > bottom) bottom = y;
      if (x < left) left = x;
      if (x > right) right = x;
    }
  }
  const pct = (value, of) => Math.round((value / of) * 1000) / 10;
  rows.push(`  '${file.replace(/\.png$/, '')}': [${pct(top, h)}, ${pct(w - 1 - right, w)}, ${pct(h - 1 - bottom, h)}, ${pct(left, w)}],`);
}

writeFileSync(OUT, `/*
  GENERATED by scripts/measure-badge-art.mjs -- do not edit by hand.

  Where each badge's artwork is drawn on its canvas, as insets from the
  top, right, bottom and left edges in percent. The coin clips its plate
  and rim to these, so they never show past the artwork's own frame.
*/

export type ArtBounds = readonly [top: number, right: number, bottom: number, left: number];

export const BADGE_ART_BOUNDS: Readonly<Record<string, ArtBounds>> = {
${rows.join('\n')}
};
`);
console.log(`Measured ${rows.length} badges into ${OUT}`);
